    private void RegistraseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistraseActionPerformed
    String nombre = txtNombre.getText().trim();
    String apellido = txtApellido.getText().trim();
    String contrasena = new String(txtContrasena.getPassword()).trim();
    String confirmar = new String(txtConfirmar.getPassword()).trim();
    
    if (nombre.isEmpty() || apellido.isEmpty() || contrasena.isEmpty() || confirmar.isEmpty()){
        JOptionPane.showMessageDialog(this, "Los campos estan vacios", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        }
    
    if (!contrasena.equals(confirmar)){
        JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden", "Contraseñas incorrectas", JOptionPane.WARNING_MESSAGE);
        }
    
    if (controlador.existeUsuario(nombre, apellido)){
        JOptionPane.showMessageDialog(this, "El usuario ingresado ya esta registrado", "Usuario ya existente", JOptionPane.WARNING_MESSAGE);
        }
    
    boolean registrado = controlador.registrar(nombre, apellido, contrasena, confirmar);
        if (registrado) {
            JOptionPane.showMessageDialog(this, "El usuario a sido registrado.","Registro exitoso",JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_RegistraseActionPerformed

