    //Iniciar sesion y boton (ENTRAR)
    private void EntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EntrarActionPerformed
        String nombre = TxtNombre.getText().trim();
        String apellido = TxtApellido.getText().trim();
        String contrasena = new String(TxtPassword.getPassword());
        
        //Verifica que los campos no esten vacios
        if (nombre.isEmpty() || apellido.isEmpty() || contrasena.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,"Por favor complete todos los campos", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }
        //Llama al controlador
        controlador.Usuario usuario = controlador.autenticar(nombre, apellido, contrasena);
        //Verifica si los campos son correctos
    if (usuario == null) {
        JOptionPane.showMessageDialog(
            this,
            "Nombre, apellido o contraseña incorrectos.",
            "Error de inicio de sesión",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    if (usuario.esAdmin()) {
        JOptionPane.showMessageDialog(
            this,
            "Bienvenido Administrador (" + usuario.id + ")", "Acceso permitido",
            JOptionPane.INFORMATION_MESSAGE
        );
        // Aquí abrirás más adelante la ventana del administrador
    } else {
        JOptionPane.showMessageDialog(
            this,
            "Bienvenido, " + usuario.nombre + " (" + usuario.id + ")", "Acceso concedido", JOptionPane.INFORMATION_MESSAGE
        );

        MenuPrincipal menu = new MenuPrincipal(usuario);
        menu.setVisible(true);
        this.dispose(); // Cierra la ventana de inicio de sesión
    }
    }//GEN-LAST:event_EntrarActionPerformed

