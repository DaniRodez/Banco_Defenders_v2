    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        
try {
    // Obtener el monto ingresado
    String textoMonto = txtMonto.getText().trim();

    if (textoMonto.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingresa el monto del prestamo.");
        return;
    }

    BigDecimal monto = new BigDecimal(
            textoMonto.replace(",", ""));

    // Obtener el plazo seleccionado
    String seleccion = cmbPlazo.getSelectedItem().toString();
    int plazo = Integer.parseInt(
            seleccion.split(" ")[0]);

    // Crear el motor y calcular la tabla
    MotorAmortizacion motor = new MotorAmortizacion();

    TablaAmortizacion tabla =
            motor.calcularTabla(monto, plazo);

    // Formato de cantidades
    DecimalFormat formato =
            new DecimalFormat("#,##0.00");

    // Mostrar resumen financiero
    lblMensualidad.setText(
            "$" + formato.format(
                    tabla.getCuotaMensual()));

    lblInteresesTotal.setText(
            "$" + formato.format(
                    tabla.getTotalIntereses()));

    lblTotalPagado.setText(
            "$" + formato.format(
                    tabla.getTotalPagado()));

    // Crear modelo de la tabla
    DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{
                "Numero",
                "Saldo inicial",
                "Mensualidad",
                "Capital",
                "Interes",
                "Saldo pendiente"
            }, 0) {

        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    // Agregar las cuotas
    for (CuotaAmortizacion cuota : tabla.getCuotas()) {

        modelo.addRow(new Object[]{
            cuota.getNumero(),
            "$" + formato.format(cuota.getSaldoInicial()),
            "$" + formato.format(cuota.getMensualidad()),
            "$" + formato.format(cuota.getCapital()),
            "$" + formato.format(cuota.getInteres()),
            "$" + formato.format(cuota.getSaldoPendiente())
        });
    }

    // Mostrar tabla
    tblAmortizacion.setModel(modelo);

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Ingresa un monto numerico valido.");

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(this,
            e.getMessage());

}

    }//GEN-LAST:event_btnCalcularActionPerformed


